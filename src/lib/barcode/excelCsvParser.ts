/**
 * Chust Textile ERP - Excel va CSV Fayllarni Aqlli Tahlil Qilish (Parser) Moduli
 * 
 * Ushbu modul Excel (.xlsx, .xls) va CSV (.csv, .tsv, .txt) fayllarni qabul qilib:
 * 1. 'Model', 'Size', 'Quantity', 'Color', 'Barcode', 'Rost' ustunlarini avtomatik aniqlaydi.
 * 2. 'Quantity' (Количество / Soni) ustunini shtrix-kod chop etish navbatidagi 'copies' (nusxalar soni)ga to'g'ridan-to'g'ri bog'laydi.
 * 3. Agar faylda shtrix-kod ustuni bo'lmasa, GS1-128 / SSCC standartiga mos to'g'ri Modulo 10 nazorat raqamli kodlarni avtomatik generatsiya qiladi.
 * 4. Foydalanuvchiga qulay interaktiv ustunlarni tekshirish va tasdiqlash imkonini beradi.
 */

import * as XLSX from 'xlsx';
import { BarcodeItem, BarcodeStatus } from './types';
import { cleanSSCCDigits, validateSSCC, tryCorrectSSCC, formatSSCC, calculateSSCCCheckDigit } from './sscc';

export interface ColumnMapping {
  modelCol: string;       // Model / Mahsulot nomi / Artikul
  sizeCol: string;        // O'lcham (Размер)
  quantityCol: string;    // Soni / Miqdori / Nusxalar (Количество)
  colorCol: string;       // Rang (Цвет)
  barcodeCol: string;     // Shtrix-kod / SSCC / EAN
  rostCol: string;        // Bo'y / Rost (Рост)
  notesCol: string;       // Izoh / Qo'shimcha
}

export interface ParsedSheetData {
  fileName: string;
  sheetNames: string[];
  activeSheet: string;
  headers: string[];
  rows: Record<string, any>[];
  detectedMapping: ColumnMapping;
}

export interface ImportOptions {
  mapping: ColumnMapping;
  autoGenerateBarcodes: boolean;
  barcodePrefix?: string;     // Standart: '04640014380' (11 xonali korxona prefiksi)
  defaultCopies: number;      // Miqdor ko'rsatilmaganda qo'yiladigan nusxa (standart: 4)
  startSequence?: number;
}

export interface ParseResult {
  items: BarcodeItem[];
  stats: {
    totalRows: number;
    validBarcodes: number;
    autoGeneratedBarcodes: number;
    totalLabelCopies: number;
  };
}

