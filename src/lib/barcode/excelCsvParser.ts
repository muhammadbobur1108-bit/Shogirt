/**
 * Matn ichidan mos sinonimni aniqlash
 */
function matchesSynonym(header: string, synonyms: string[]): boolean {
  if (!header) return false;
  const clean = header.toLowerCase().replace(/[^a-zа-я0-9]/gi, '');
  return synonyms.some(syn => {
    const cleanSyn = syn.toLowerCase().replace(/[^a-zа-я0-9]/gi, '');
    return clean === cleanSyn || clean.includes(cleanSyn) || cleanSyn.includes(clean);
  });
}

/**
 * Sarlavhalar ro'yxatidan avtomatik ustunlarni xaritaga tushirish (Auto-mapping)
 */
export function detectColumnMapping(headers: string[]): ColumnMapping {
  const mapping: ColumnMapping = {
    modelCol: '',
    sizeCol: '',
    quantityCol: '',
    colorCol: '',
    barcodeCol: '',
    rostCol: '',
    notesCol: ''
  };

  const usedHeaders = new Set<string>();

  const findBestHeader = (synonyms: string[], excludeRost = false): string => {
    for (const h of headers) {
      if (usedHeaders.has(h)) continue;
      if (excludeRost && matchesSynonym(h, SYNONYMS.rost)) continue;
      if (matchesSynonym(h, synonyms)) {
        usedHeaders.add(h);
        return h;
      }
    }
    return '';
  };

  // 1. Shtrix-kod
  mapping.barcodeCol = findBestHeader(SYNONYMS.barcode);

  // 2. Miqdor / Quantity (Chop etiladigan nusxalar)
  mapping.quantityCol = findBestHeader(SYNONYMS.quantity);

  // 3. O'lcham (Size - rost bilan adashmaslik uchun)
  mapping.sizeCol = findBestHeader(SYNONYMS.size, true);

  // 4. Rost / Bo'y
  mapping.rostCol = findBestHeader(SYNONYMS.rost);

  // 5. Rang (Color)
  mapping.colorCol = findBestHeader(SYNONYMS.color);

  // 6. Model / Nomi / Artikul
  mapping.modelCol = findBestHeader(SYNONYMS.model);

  // 7. Izoh
  mapping.notesCol = findBestHeader(SYNONYMS.notes);

  return mapping;
}

/**
 * CSV matnini aniqlash va ajratuvchi belgini (comma, semicolon, tab) aniqlash
 */
function detectCsvDelimiter(text: string): string {
  const sample = text.slice(0, 2048);
  const commas = (sample.match(/,/g) || []).length;
  const semicolons = (sample.match(/;/g) || []).length;
  const tabs = (sample.match(/\t/g) || []).length;
  const pipes = (sample.match(/\|/g) || []).length;

  if (semicolons >= commas && semicolons >= tabs && semicolons >= pipes && semicolons > 0) return ';';
  if (tabs >= commas && tabs >= semicolons && tabs >= pipes && tabs > 0) return '\t';
  if (pipes >= commas && pipes >= semicolons && pipes > 0) return '|';
  return ',';
}

/**
 * Excel yoki CSV faylni o'qib umumiy tuzilmaga o'tkazish
 */
export async function parseExcelOrCsvFile(file: File | ArrayBuffer, fileName: string = 'fayl'): Promise<ParsedSheetData> {
  const buffer = file instanceof File ? await file.arrayBuffer() : file;
  
  let workbook: XLSX.WorkBook;
  try {
    // XLSX o'zi CSV, TSV va Excel formatlarini aniqlay oladi
    workbook = XLSX.read(buffer, { type: 'array', cellDates: true, raw: false });
  } catch {
    // Agar matn bo'lsa (UTF-8 yoki ANSI CSV)
    const textDecoder = new TextDecoder('utf-8');
    const text = textDecoder.decode(buffer);
    const delimiter = detectCsvDelimiter(text);
    workbook = XLSX.read(text, { type: 'string', FS: delimiter });
  }

  const sheetNames = workbook.SheetNames;
  if (!sheetNames || sheetNames.length === 0) {
    throw new Error('Faylda sahifalar topilmadi yoki fayl bo\'sh');
  }

  const activeSheet = sheetNames[0];
  const worksheet = workbook.Sheets[activeSheet];
  if (!worksheet) {
    throw new Error('Tanlangan sahifa bo\'sh');
  }

  // Qatorlarni o'qish (JSON formatida sarlavhalar bilan)
  const rawRows: Record<string, any>[] = XLSX.utils.sheet_to_json(worksheet, { defval: '' });
  
  // Agar sarlavhalar bo'sh bo'lsa yoki 2D massiv kerak bo'lsa
  let headers: string[] = [];
  if (rawRows.length > 0) {
    headers = Object.keys(rawRows[0]).filter(h => !h.startsWith('__EMPTY'));
  }

  // Agar sarlavhalar to'g'ri topilmagan bo'lsa, birinchi qatordan olamiz
  if (headers.length === 0) {
    const matrix: any[][] = XLSX.utils.sheet_to_json(worksheet, { header: 1 });
    if (matrix.length > 0 && Array.isArray(matrix[0])) {
      headers = matrix[0].map(c => String(c || '').trim()).filter(Boolean);
    }
  }

  const detectedMapping = detectColumnMapping(headers);

  return {
    fileName,
    sheetNames,
    activeSheet,
    headers,
    rows: rawRows,
    detectedMapping
  };
}

/**
 * 18 xonali to'g'ri SSCC shtrix-kodini generatsiya qilish (Modulo 10 nazorati bilan)
 */
export function generateValidSSCCBarcode(sequence: number, companyPrefix: string = '04640014380'): { sscc: string; formatted: string } {
  // 11 xonali prefiks + 6 xonali ketma-ketlik = 17 xona
  const seqPadded = String(Math.abs(sequence) % 1000000).padStart(6, '0');
  const base17 = (companyPrefix + seqPadded).slice(0, 17);
  const checkDigit = calculateSSCCCheckDigit(base17);
  const sscc = `${base17}${checkDigit}`;
  return {
    sscc,
    formatted: `(00)${sscc}`
  };
}

/**
 * Qatorlarni BarcodeItem ro'yxatiga o'tkazish va navbatga joylash
 */
export function convertMappedRowsToBarcodeItems(
  rows: Record<string, any>[],
  options: ImportOptions,
  sourceFileName: string = 'Import_Fayl'
): ParseResult {
  const { mapping, autoGenerateBarcodes, barcodePrefix = '04640014380', defaultCopies = 4 } = options;
  const items: BarcodeItem[] = [];

  let validBarcodes = 0;
  let autoGeneratedBarcodes = 0;
  let totalLabelCopies = 0;
  let sequenceTracker = Math.floor(Date.now() / 1000) % 900000 + 100000;

  rows.forEach((row, idx) => {
    // 1. Model / Mahsulot
    const model = mapping.modelCol && row[mapping.modelCol] !== undefined ? String(row[mapping.modelCol]).trim() : '';

    // 2. O'lcham (Size)
    const size = mapping.sizeCol && row[mapping.sizeCol] !== undefined ? String(row[mapping.sizeCol]).trim() : '';

    // 3. Rang (Color)
    const color = mapping.colorCol && row[mapping.colorCol] !== undefined ? String(row[mapping.colorCol]).trim() : '';

    // 4. Bo'y (Rost)
    const rost = mapping.rostCol && row[mapping.rostCol] !== undefined ? String(row[mapping.rostCol]).trim() : '170-176';

    // 5. Miqdor / Quantity -> Copies
    let rawQty = 0;
    if (mapping.quantityCol && row[mapping.quantityCol] !== undefined) {
      const parsedNum = parseFloat(String(row[mapping.quantityCol]).replace(/[^0-9.]/g, ''));
      if (!isNaN(parsedNum) && parsedNum > 0) {
        rawQty = Math.round(parsedNum);
      }
    }
    const copies = rawQty > 0 ? rawQty : defaultCopies;
    totalLabelCopies += copies;

    // 6. Shtrix-kod
    let rawBarcode = '';
    if (mapping.barcodeCol && row[mapping.barcodeCol] !== undefined) {
      rawBarcode = String(row[mapping.barcodeCol]).trim();
    }

    let sscc = '';
    let formattedCode = '';
    let status: BarcodeStatus = 'OK';
    let notes = '';

    const cleaned = cleanSSCCDigits(rawBarcode);

    if (cleaned.length === 18 && validateSSCC(cleaned)) {
      // Haqiqiy 18 xonali to'g'ri SSCC
      sscc = cleaned;
      formattedCode = formatSSCC(cleaned);
      status = 'OK';
      validBarcodes++;
      notes = `Excel orqali import qilindi (${sourceFileName})`;
    } else if (cleaned.length === 18) {
      // 18 xonali, lekin nazorat raqami noto'g'ri bo'lishi mumkin
      const corrected = tryCorrectSSCC(cleaned);
      if (corrected && corrected.wasCorrected) {
        sscc = corrected.corrected;
        formattedCode = formatSSCC(corrected.corrected);
        status = 'tuzatildi';
        validBarcodes++;
        notes = `Nazorat raqami avtomatik to'g'rilandi: ${corrected.details}`;
      } else {
        sscc = cleaned;
        formattedCode = formatSSCC(cleaned);
        status = 'nazorat_mos_emas';
        notes = 'SSCC nazorat raqami mos kelmadi';
      }
    } else if (cleaned.length > 0 && cleaned.length !== 18) {
      // Boshqa turdagi shtrix-kod (masalan 13 xonali EAN-13)
      sscc = cleaned;
      formattedCode = cleaned;
      status = 'OK';
      validBarcodes++;
      notes = `Format: ${cleaned.length} xonali kod`;
    } else if (autoGenerateBarcodes) {
      // Shtrix-kod ustuni bo'sh yoki topilmadi: avtomatik to'g'ri GS1-128 / SSCC yaratamiz
      const generated = generateValidSSCCBarcode(sequenceTracker++, barcodePrefix);
      sscc = generated.sscc;
      formattedCode = generated.formatted;
      status = 'OK';
      autoGeneratedBarcodes++;
      notes = `Avtomatik yaratilgan GS1-128/SSCC kod (Modulo 10)`;
    } else {
      sscc = '';
      formattedCode = '';
      status = 'oqilmadi';
      notes = 'Shtrix-kod kiritilmagan';
    }

    const item: BarcodeItem = {
      id: `bc-queue-${Date.now()}-${idx}-${Math.random().toString(36).substring(2, 6)}`,
      fileName: model || `Qator #${idx + 1}`,
      rawCode: rawBarcode || sscc,
      sscc,
      formattedCode,
      model,
      color,
      size,
      rost,
      quantity: rawQty > 0 ? rawQty : copies,
      copies,
      status,
      notes,
      createdAt: new Date().toISOString()
    };

    items.push(item);
  });

  return {
    items,
    stats: {
      totalRows: rows.length,
      validBarcodes,
      autoGeneratedBarcodes,
      totalLabelCopies
    }
  };
}

